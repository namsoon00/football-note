String _normalizeRosterLookupKey(String value) {
  return _foldRosterLookupDiacritics(value)
      .trim()
      .toLowerCase()
      .replaceAll(RegExp(r'[\s._-]+'), ' ')
      .replaceAll(RegExp(r'[^a-z0-9가-힣 ]'), '')
      .replaceAll(RegExp(r'\s+'), ' ');
}

String _foldRosterLookupDiacritics(String value) {
  return value
      .replaceAll(RegExp(r'[ÀÁÂÃÄÅĀĂĄàáâãäåāăą]'), 'a')
      .replaceAll(RegExp(r'[ÇĆČçćč]'), 'c')
      .replaceAll(RegExp(r'[ÐĐðđ]'), 'd')
      .replaceAll(RegExp(r'[ÈÉÊËĒĖĘĚèéêëēėęě]'), 'e')
      .replaceAll(RegExp(r'[Ğğ]'), 'g')
      .replaceAll(RegExp(r'[ÌÍÎÏĪĮìíîïīį]'), 'i')
      .replaceAll(RegExp(r'[Łł]'), 'l')
      .replaceAll(RegExp(r'[ÑŃñń]'), 'n')
      .replaceAll(RegExp(r'[ÒÓÔÕÖØŌŐòóôõöøōő]'), 'o')
      .replaceAll(RegExp(r'[ŚŞŠśşš]'), 's')
      .replaceAll(RegExp(r'[ÙÚÛÜŪŮŰùúûüūůű]'), 'u')
      .replaceAll(RegExp(r'[ÝŸýÿ]'), 'y')
      .replaceAll(RegExp(r'[ŽŹŻžźż]'), 'z')
      .replaceAll('Æ', 'AE')
      .replaceAll('æ', 'ae')
      .replaceAll('Œ', 'OE')
      .replaceAll('œ', 'oe')
      .replaceAll('ß', 'ss');
}

